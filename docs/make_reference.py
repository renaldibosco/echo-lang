"""Regenerates section 10 of LANGUAGE.md from the code: python docs/make_reference.py"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "python"))

from echo.modules import GLOBALS, MODULES, build  # noqa: E402
from echo.values import Builtin, show  # noqa: E402

MARK = "<!-- generated by docs/make_reference.py; do not edit by hand -->"


def row(qual, value):
    if isinstance(value, Builtin):
        doc = value.doc or qual
        m = re.match(r"^([\w.]+\([^)]*\))\s*(.*)$", doc)
        call, text = (m.group(1), m.group(2)) if m else (qual + "(...)", doc)
        return "| `%s` | %s |" % (call, text.replace("|", "\\|"))
    return "| `%s` | constant: `%s` |" % (qual, show(value, True)[:40])


def main():
    build()
    out = [MARK, "", "### Global functions", "", "| Function | What it does |", "|---|---|"]
    out += [row(n, GLOBALS[n]) for n in sorted(GLOBALS)]
    for m in sorted(MODULES, key=lambda m: (m != "bio", m)):
        mod = MODULES[m]
        out += ["", "### %s — %s" % (m, mod.doc), "", "| Function | What it does |", "|---|---|"]
        out += [row("%s.%s" % (m, n), mod.members[n]) for n in sorted(mod.members)]
    path = os.path.join(HERE, "LANGUAGE.md")
    text = open(path, encoding="utf-8").read()
    text = text.split(MARK)[0].rstrip() + "\n\n" + "\n".join(out) + "\n"
    open(path, "w", encoding="utf-8", newline="\n").write(text)
    print("updated", path)


if __name__ == "__main__":
    main()
